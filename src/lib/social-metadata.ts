import type { Metadata } from "next";
import { siteConfig } from "@/lib/site-config";

// ─────────────────────────────────────────────────────────────────
// Social (Open Graph / Twitter) metadata for chapter pages.
//
// Next.js REPLACES a parent segment's `openGraph` object instead of merging
// it, so a page that sets its own openGraph loses the root layout's image,
// siteName and locale unless it repeats them (audit finding SEO-2). This
// helper is the single place that builds that block for every chapter
// overview page and every chapter resource page.
//
// Images: public/og/class-{11|12}/{slug}.png (1200 × 630), generated by
// scripts/generate-og-images.mjs from the licensed illustrations recorded
// in assets/og-sources/sources.json (credits: docs/ASSET_CREDITS.md).
// Resource pages (notes, DPP, PYQ, …) reuse their chapter's image.
//
// The root layout (homepage and all non-chapter pages) is NOT changed and
// keeps its own metadata.
// ─────────────────────────────────────────────────────────────────

export const OG_IMAGE_WIDTH = 1200;
export const OG_IMAGE_HEIGHT = 630;

/** Same values the root layout uses, so chapter pages stay consistent with it. */
const SITE_NAME = siteConfig.name;
const LOCALE = "en_IN";

export type ChapterClass = "11" | "12";

/** Site-relative URL of a chapter's Open Graph image (resolved against metadataBase). */
export function chapterOgImagePath(cls: ChapterClass, slug: string): string {
  return `/og/class-${cls}/${slug}.png`;
}

export type ChapterSocialInput = {
  cls: ChapterClass;
  slug: string;
  chapterName: string;
  title: string;
  description: string;
  /** Page path, e.g. "/class-11/kinematics" or "/class-11/kinematics/notes". */
  path: string;
};

/** openGraph + twitter metadata for a chapter overview or chapter resource page. */
export function chapterSocialMetadata({
  cls,
  slug,
  chapterName,
  title,
  description,
  path,
}: ChapterSocialInput): Pick<Metadata, "openGraph" | "twitter"> {
  const image = {
    url: chapterOgImagePath(cls, slug),
    width: OG_IMAGE_WIDTH,
    height: OG_IMAGE_HEIGHT,
    alt: `${chapterName}: Class ${cls} Physics for JEE and NEET, ${SITE_NAME}`,
  };
  return {
    openGraph: {
      title,
      description,
      url: path,
      type: "article",
      siteName: SITE_NAME,
      locale: LOCALE,
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [image.url],
    },
  };
}
